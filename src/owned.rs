//! The registers an applied [`Config`] owns: what `verify` reads back and compares. Pure code, no bus
//! and no allocation. Only [`Space`] and [`Mismatch`] (the payload of
//! [`Error::ConfigMismatch`](crate::Error::ConfigMismatch)) are public; the list itself is crate-private.
//!
//! The expected values come from the functions of [`crate::image`], the ones [`crate::plan`] writes
//! with: there is no second table. A register the plan only modifies under a mask is owned under that
//! mask. The list depends on the [`Config`] only, so it is the same whether the configuration was
//! applied by [`crate::Plan::after_reset`] or by [`crate::Plan::reconfigure`]: after a reset the
//! registers the post-reset plan leaves alone hold their reset value, which is the image value.
//!
//! Order: the direct registers by ascending address, then the indirect registers by ascending
//! address. The twelve user-offset registers are owned under the applied [`crate::Offsets`]: the low
//! bytes whole, the high registers under bits 5:0 (bits 7:6 are reserved, 20.2, p189).
//!
//! Bits left out of a mask, because they clear themselves, report status, are commands, are reserved
//! or are outside this crate's scope:
//! - FIFO_CONFIG2 bit 7 FIFO_FLUSH, a command (16.31, p81); bits 6:4 and 2:0 are reserved (p81), so
//!   bit 5, which reads 1 at reset, is not compared.
//! - RTC_CONFIG bit 6 RTC_ALIGN, "re-align command is generated by writing 1" (16.37, p86); the
//!   datasheet does not say that it reads back as written. Bits 4:0 and 7 are reserved.
//! - Every other bit of a register that this crate keeps at its reset value (reserved or out of
//!   scope fields: p66; 16.17 p70, 16.26 p78, 16.32 p82, 16.33 p83, 16.34 p84, 16.48 p93,
//!   19.47 p178, 19.52 p181, 20.7 p190, 20.11 p192, 21.7 p194).
//! - The soft-reset bit SOFT_RST and the IREG_DONE status bit of REG_MISC2 (16.84, p109), the
//!   status flags (INT1_STATUS0, 16.24, p76) and the data registers are not configuration and not
//!   listed.
//! - IOC_PAD_SCENARIO_OVRD (0x31) is not in the datasheet (vendor), so nothing says it reads back:
//!   it is not listed even when the external clock is on.

use crate::config::{ClockSource, Config};
use crate::image;
use crate::offsets::Offsets;
use crate::reg;

/// Register space of an owned register.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
#[non_exhaustive]
pub enum Space {
    /// A direct register (bank 0), one SPI transaction to read.
    #[default]
    Direct,
    /// An indirect register behind IREG_ADDR / IREG_DATA (13, p55), two transactions to read.
    Indirect,
}

/// One owned register: where it is, which bits are compared and the value they must hold.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
#[non_exhaustive]
pub(crate) struct OwnedRegister {
    /// Register space.
    pub space: Space,
    /// Direct register address, or indirect register address (bank base plus offset).
    pub register: u16,
    /// The bits that are compared.
    pub mask: u8,
    /// The value the compared bits must hold; zero outside `mask`.
    pub expected: u8,
}

/// A register that did not hold the applied configuration (the payload of
/// [`Error::ConfigMismatch`](crate::Error::ConfigMismatch)).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
#[non_exhaustive]
pub struct Mismatch {
    /// Register space.
    pub space: Space,
    /// Direct register address, or indirect register address (bank base plus offset).
    pub register: u16,
    /// The bits that were compared.
    pub mask: u8,
    /// The value the compared bits must hold (masked); zero outside `mask`.
    pub expected: u8,
    /// The whole register byte as read the second time, not masked: the bits outside `mask` are
    /// included, so a caller sees the status and reserved bits as the device returned them.
    pub found: u8,
}

/// Room for the longest list: 15 direct and 19 indirect registers (external clock, twelve offsets).
pub(crate) const OWNED_CAPACITY: usize = 34;

const NONE: OwnedRegister = OwnedRegister {
    space: Space::Direct,
    register: 0,
    mask: 0,
    expected: 0,
};

/// An ordered, bounded list of [`OwnedRegister`]s.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct OwnedRegisters {
    items: [OwnedRegister; OWNED_CAPACITY],
    len: usize,
}

impl OwnedRegisters {
    /// The owned registers, in the order `verify` reads them.
    pub(crate) fn registers(&self) -> &[OwnedRegister] {
        self.items.get(..self.len).unwrap_or_default()
    }

    /// Number of owned registers.
    #[cfg(test)]
    pub(crate) const fn len(&self) -> usize {
        self.len
    }

    /// Whether the list is empty (it never is).
    #[cfg(test)]
    pub(crate) const fn is_empty(&self) -> bool {
        self.len == 0
    }

    #[cfg(test)]
    fn direct_len(&self) -> usize {
        self.registers()
            .iter()
            .filter(|r| r.space == Space::Direct)
            .count()
    }

    #[cfg(test)]
    fn indirect_len(&self) -> usize {
        self.len - self.direct_len()
    }

    /// The SPI transactions of a `verify` that finds no mismatch: one per direct register, two per
    /// indirect register.
    #[cfg(test)]
    pub(crate) fn verify_transactions(&self) -> usize {
        self.direct_len() + 2 * self.indirect_len()
    }

    fn push(&mut self, space: Space, register: u16, mask: u8, image: u8) {
        if let Some(slot) = self.items.get_mut(self.len) {
            *slot = OwnedRegister {
                space,
                register,
                mask,
                expected: image & mask,
            };
            self.len += 1;
        }
    }

    fn direct(&mut self, register: u8, mask: u8, image: u8) {
        self.push(Space::Direct, u16::from(register), mask, image);
    }

    fn indirect(&mut self, register: u16, mask: u8, image: u8) {
        self.push(Space::Indirect, register, mask, image);
    }
}

/// The registers `config` and the applied `offsets` own. `config` should be valid
/// ([`Config::validate`]) and `offsets` in range; the list is built from their images either way.
pub(crate) fn owned_registers(c: &Config, offsets: &Offsets) -> OwnedRegisters {
    let mut o = OwnedRegisters {
        items: [NONE; OWNED_CAPACITY],
        len: 0,
    };
    // PWR_MGMT0 GYRO_MODE, ACCEL_MODE (16.17, p70).
    o.direct(reg::PWR_MGMT0, reg::PWR_MGMT0_FIELDS, image::pwr_mgmt0(c));
    // INT1_CONFIG0, all eight enables (16.21, p72-p73).
    o.direct(
        reg::INT1_CONFIG0,
        reg::INT1_CONFIG0_FIELDS,
        image::int1_config0(c),
    );
    // INT1_CONFIG2 drive, mode, polarity (16.23, p75).
    o.direct(
        reg::INT1_CONFIG2,
        reg::INT1_CONFIG2_FIELDS,
        image::int1_config2(c),
    );
    // ACCEL_CONFIG0 (16.26, p78) and GYRO_CONFIG0 (16.27, p79).
    o.direct(
        reg::ACCEL_CONFIG0,
        reg::ACCEL_CONFIG0_FIELDS,
        image::accel_config0(c),
    );
    o.direct(
        reg::GYRO_CONFIG0,
        reg::GYRO_CONFIG0_FIELDS,
        image::gyro_config0(c),
    );
    // FIFO_CONFIG0 mode and depth (16.28, p80); the watermark bytes (16.29, p80; 16.30, p81).
    o.direct(
        reg::FIFO_CONFIG0,
        reg::FIFO_CONFIG0_FIELDS,
        image::fifo_config0(c),
    );
    let [wm_low, wm_high] = image::fifo_watermark(c);
    o.direct(reg::FIFO_CONFIG1_0, 0xFF, wm_low);
    o.direct(reg::FIFO_CONFIG1_1, 0xFF, wm_high);
    // FIFO_CONFIG2: only FIFO_WR_WM_GT_TH; FIFO_FLUSH is a command and the rest is reserved
    // (16.31, p81).
    o.direct(
        reg::FIFO_CONFIG2,
        reg::FIFO_WR_WM_GT_TH,
        image::fifo_config2(c),
    );
    // FIFO_CONFIG3 content and interface enable, as left by the plan (16.32, p82).
    o.direct(
        reg::FIFO_CONFIG3,
        reg::FIFO_CONFIG3_FIELDS,
        image::fifo_config3(c, true),
    );
    // FIFO_CONFIG4 timestamp field (16.33, p83); TMST_WOM_CONFIG resolution (16.34, p84).
    o.direct(
        reg::FIFO_CONFIG4,
        reg::FIFO_CONFIG4_FIELDS,
        image::fifo_config4(c),
    );
    o.direct(
        reg::TMST_WOM_CONFIG,
        reg::TMST_WOM_CONFIG_FIELDS,
        image::tmst_wom_config(c),
    );
    // RTC_CONFIG: RTC_MODE only; RTC_ALIGN is a command (16.37, p86).
    o.direct(reg::RTC_CONFIG, reg::RTC_MODE, image::rtc_mode(c));
    // ODR_DECIMATE_CONFIG (16.39, p87); DRIVE_CONFIG0 slew (16.48, p93).
    o.direct(
        reg::ODR_DECIMATE_CONFIG,
        reg::ODR_DECIMATE_CONFIG_FIELDS,
        image::odr_decimate_config(c),
    );
    o.direct(
        reg::DRIVE_CONFIG0,
        reg::DRIVE_CONFIG0_FIELDS,
        image::drive_config0(c),
    );

    // SMC_CONTROL_0 ACCEL_LP_CLK_SEL and TMST_EN (19.47, p178-p179).
    o.indirect(
        reg::SMC_CONTROL_0,
        reg::ACCEL_LP_CLK_SEL | reg::TMST_EN,
        image::accel_lp_clk_sel(c) | image::smc_timestamp(c),
    );
    // SIFS_I3C_STC_CFG I3C_STC_MODE must be 0 for RTC mode (19.51, p180; 16.37, p86); the plan only
    // writes it with the external clock.
    if c.clock == ClockSource::ExternalClkin {
        o.indirect(reg::SIFS_I3C_STC_CFG, reg::I3C_STC_MODE, 0);
    }
    // INT0_TPULSE_DURATION (19.52, p181).
    o.indirect(
        reg::INT_PULSE_MIN_ON_INTF0,
        reg::INT_PULSE_MIN_ON_INTF0_FIELDS,
        image::int1_pulse_width(c),
    );
    // GYRO_X, Y, Z_OFFUSER, low byte and bits 13:8 (20.1-20.6, p189-p190): the applied offsets, in
    // address order between INT0_TPULSE_DURATION and GYRO_SRC_CTRL.
    let [gxl, gxh, gyl, gyh, gzl, gzh, axl, axh, ayl, ayh, azl, azh] = offsets.registers();
    for (addr, value, mask) in [gxl, gxh, gyl, gyh, gzl, gzh] {
        o.indirect(addr, mask, value);
    }
    // GYRO_SRC_CTRL (20.7, p190), GYRO_UI_LPFBW_SEL (20.11, p192).
    o.indirect(
        reg::IPREG_SYS1_REG_166,
        reg::GYRO_SRC_CTRL_MASK,
        image::gyro_src_ctrl(c),
    );
    o.indirect(
        reg::IPREG_SYS1_REG_172,
        reg::GYRO_UI_LPFBW_MASK,
        image::gyro_ui_lpfbw(c),
    );
    // ACCEL_X, Y, Z_OFFUSER (21.1-21.6, p193-p194).
    for (addr, value, mask) in [axl, axh, ayl, ayh, azl, azh] {
        o.indirect(addr, mask, value);
    }
    // ACCEL_SRC_CTRL (21.7, p194), ACCEL_UI_LPFBW_SEL (21.10, p196).
    o.indirect(
        reg::IPREG_SYS2_REG_123,
        reg::ACCEL_SRC_CTRL_MASK,
        image::accel_src_ctrl(c),
    );
    o.indirect(
        reg::IPREG_SYS2_REG_131,
        reg::ACCEL_UI_LPFBW_MASK,
        image::accel_ui_lpfbw(c),
    );
    o
}
